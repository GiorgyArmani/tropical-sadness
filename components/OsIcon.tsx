export type OsIconName = keyof typeof ART

// Un <path> por color: cada fila se junta en tramos horizontales de píxeles iguales
const build = (art: string) => {
  const byColor = new Map<string, string>()
  art
    .trim()
    .split(/\s+/)
    .forEach((row, y) => {
      for (let x = 0; x < row.length; ) {
        const ch = row[x]
        let w = 1
        while (row[x + w] === ch) w++
        if (ch !== ".") byColor.set(ch, (byColor.get(ch) ?? "") + `M${x} ${y}h${w}v1h-${w}z`)
        x += w
      }
    })
  return [...byColor].map(([ch, d]) => ({ fill: PALETTE[ch], d }))
}

const ICONS = Object.fromEntries(Object.entries(ART).map(([name, art]) => [name, build(art)])) as Record<
  OsIconName,
  ReturnType<typeof build>
>

export default function OsIcon({ name, className = "h-4 w-4" }: { name: OsIconName; className?: string }) {
  return (
    <svg viewBox="0 0 16 16" className={`shrink-0 ${className}`} shapeRendering="crispEdges" aria-hidden="true">
      {ICONS[name].map((p) => (
        <path key={p.fill} fill={p.fill} d={p.d} />
      ))}
    </svg>
  )
}
